#!/usr/bin/env node
// scripts/hk-codegen.mjs — Contract-First CodeGen Engine (Zero-dependency Node 22+)
// Generates synchronized TypeScript interfaces (for Next.js) and Kotlin @Serializable data classes (for Android).
import { readFileSync, writeFileSync, readdirSync, existsSync, mkdirSync } from 'node:fs';
import { resolve, join } from 'node:path';

const ROOT = process.cwd();
const CONTRACTS_DIR = resolve(ROOT, 'contracts');
const TS_OUT_DIR = resolve(ROOT, 'src', 'types', 'contracts');
const TS_OUT_FILE = join(TS_OUT_DIR, 'generated.ts');

function toKotlinType(prop) {
  if (prop.type === 'string') {
    if (Array.isArray(prop.enum)) return prop.enumName || 'String';
    return 'String';
  }
  if (prop.type === 'number' || prop.type === 'integer') return prop.isFloat ? 'Double' : 'Long';
  if (prop.type === 'boolean') return 'Boolean';
  if (prop.type === 'array') {
    const itemType = toKotlinType(prop.items || { type: 'string' });
    return `List<${itemType}>`;
  }
  if (prop.type === 'object') return prop.objectName || 'Map<String, String>';
  return 'String';
}

function toTsType(prop) {
  if (prop.type === 'string') {
    if (Array.isArray(prop.enum)) return prop.enum.map(v => `'${v}'`).join(' | ');
    return 'string';
  }
  if (prop.type === 'number' || prop.type === 'integer') return 'number';
  if (prop.type === 'boolean') return 'boolean';
  if (prop.type === 'array') {
    const itemType = toTsType(prop.items || { type: 'string' });
    return `${itemType}[]`;
  }
  if (prop.type === 'object') return prop.objectName || 'Record<string, unknown>';
  return 'unknown';
}

function generate() {
  if (!existsSync(CONTRACTS_DIR)) {
    console.log('ℹ️  hk-codegen: no contracts/ directory found. Creating empty template...');
    mkdirSync(CONTRACTS_DIR, { recursive: true });
    writeFileSync(
      join(CONTRACTS_DIR, 'models.json'),
      JSON.stringify({
        $schema: 'http://json-schema.org/draft-07/schema#',
        title: 'HKContractDefinitions',
        entities: [
          {
            name: 'SystemAlert',
            description: 'Cross-platform system alert model shared between Web and Android',
            properties: {
              id: { type: 'string' },
              title: { type: 'string' },
              category: { type: 'string', enum: ['SECURITY', 'PERFORMANCE', 'SYSTEM', 'CRITICAL'] },
              severity: { type: 'string', enum: ['LOW', 'MEDIUM', 'HIGH', 'CRITICAL'] },
              score: { type: 'integer' },
              isActive: { type: 'boolean' },
              tags: { type: 'array', items: { type: 'string' } },
              timestamp: { type: 'number' }
            },
            required: ['id', 'title', 'category', 'severity', 'score', 'isActive', 'timestamp']
          }
        ]
      }, null, 2),
      'utf8'
    );
  }

  const contractFiles = readdirSync(CONTRACTS_DIR).filter(f => f.endsWith('.json'));
  if (contractFiles.length === 0) {
    console.log('⚠️ hk-codegen: no .json schema contracts found in contracts/');
    return;
  }

  let tsOutput = `// ----------------------------------------------------------------------------\n// 🤖 AUTOGENERATED BY HK-CODEGEN · DO NOT EDIT DIRECTLY\n// Source: contracts/*.json · Run 'npm run codegen' to regenerate\n// ----------------------------------------------------------------------------\n\n`;
  let kotlinOutput = `// ----------------------------------------------------------------------------\n// 🤖 AUTOGENERATED BY HK-CODEGEN · DO NOT EDIT DIRECTLY\n// Source: contracts/*.json · Run 'npm run codegen' to regenerate\n// ----------------------------------------------------------------------------\npackage in.pausepoint.shield.model.generated\n\nimport kotlinx.serialization.Serializable\nimport kotlinx.serialization.SerialName\n\n`;

  let totalTypes = 0;

  for (const file of contractFiles) {
    const raw = readFileSync(join(CONTRACTS_DIR, file), 'utf8');
    const contract = JSON.parse(raw);
    const entities = contract.entities || [];

    for (const entity of entities) {
      totalTypes++;
      const { name, description, properties = {}, required = [] } = entity;

      // --- TypeScript ---
      if (description) tsOutput += `/** ${description} */\n`;
      tsOutput += `export interface ${name} {\n`;
      for (const [key, prop] of Object.entries(properties)) {
        const isOptional = !required.includes(key);
        const optMarker = isOptional ? '?' : '';
        const tsType = toTsType(prop);
        tsOutput += `  ${key}${optMarker}: ${tsType};\n`;
      }
      tsOutput += `}\n\n`;

      // Generate string unions for enums
      for (const [key, prop] of Object.entries(properties)) {
        if (Array.isArray(prop.enum)) {
          const enumTypeName = `${name}${key.charAt(0).toUpperCase() + key.slice(1)}`;
          tsOutput += `export type ${enumTypeName} = ${prop.enum.map(v => `'${v}'`).join(' | ')};\n\n`;
        }
      }

      // --- Kotlin ---
      if (description) kotlinOutput += `/**\n * ${description}\n */\n`;
      kotlinOutput += `@Serializable\ndata class ${name}(\n`;
      const propEntries = Object.entries(properties);
      propEntries.forEach(([key, prop], idx) => {
        const isOptional = !required.includes(key);
        let ktType = toKotlinType(prop);
        if (isOptional) ktType = `${ktType}? = null`;
        const comma = idx === propEntries.length - 1 ? '' : ',';
        kotlinOutput += `    @SerialName("${key}") val ${key}: ${ktType}${comma}\n`;
      });
      kotlinOutput += `)\n\n`;
    }
  }

  // Write TypeScript
  mkdirSync(TS_OUT_DIR, { recursive: true });
  writeFileSync(TS_OUT_FILE, tsOutput, 'utf8');

  // Write Kotlin (both in standalone android-contracts/ and inside android/app if present)
  const ktDirs = [
    resolve(ROOT, 'android-contracts', 'generated'),
    resolve(ROOT, 'android', 'app', 'src', 'main', 'java', 'in', 'pausepoint', 'shield', 'model', 'generated')
  ];

  for (const ktDir of ktDirs) {
    try {
      if (ktDir.includes('android-contracts') || existsSync(resolve(ROOT, 'android', 'app'))) {
        mkdirSync(ktDir, { recursive: true });
        writeFileSync(join(ktDir, 'Models.kt'), kotlinOutput, 'utf8');
      }
    } catch {
      // Best-effort for Android dir if not yet present
    }
  }

  console.log(`✅ hk-codegen: generated TypeScript (${totalTypes} entities) -> ${TS_OUT_FILE}`);
}

generate();
